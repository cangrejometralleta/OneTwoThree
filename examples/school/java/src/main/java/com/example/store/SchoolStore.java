package com.example.store;

import com.example.app.CourseStore;
import com.example.app.StudentStore;
import com.example.school.Course;
import com.example.school.CourseCode;
import com.example.school.CourseId;
import com.example.school.Errors;
import com.example.school.FullName;
import com.example.school.Page;
import com.example.school.Rut;
import com.example.school.Student;
import com.example.school.StudentId;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * SchoolStore Keeps Students and Courses in one H2 File through JDBC.
 * This Package is the only one that Speaks SQL; JDBC Finds the Driver at Runtime.
 * Reference: https://h2database.com/html/features.html#database_url
 */
public final class SchoolStore implements StudentStore, CourseStore {

  /** UNIQUE_VIOLATION is the SQLState a unique Index Answers with. */
  private static final String UNIQUE_VIOLATION = "23505";

  private static final String STUDENT_COLUMNS = "id, rut, name, age, course_id";
  private static final String COURSE_COLUMNS = "id, code, name";

  private final String url;

  private SchoolStore(String url) {
    this.url = url;
  }

  /**
   * openSchoolStore Opens the Database and Brings its Tables up to Date.
   * The Path Names a Base; H2 Appends its own Suffix to it.
   */
  public static SchoolStore openSchoolStore(Path base) throws SQLException {
    SchoolStore store = new SchoolStore("jdbc:h2:file:" + base.toAbsolutePath() + ";DB_CLOSE_DELAY=-1");
    try (Connection connection = store.connect(); Statement statement = connection.createStatement()) {
      statement.execute("""
          CREATE TABLE IF NOT EXISTS student_rows (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            rut VARCHAR NOT NULL UNIQUE,
            name VARCHAR NOT NULL,
            age BIGINT NOT NULL,
            course_id BIGINT NOT NULL)""");
      statement.execute("""
          CREATE TABLE IF NOT EXISTS course_rows (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code VARCHAR NOT NULL,
            name VARCHAR NOT NULL)""");
    }

    return store;
  }

  /** insertStudentRow Writes a new Student and Returns it Numbered; the unique Index Proves the Rut. */
  @Override
  public Student insertStudentRow(Student student) {
    StudentRow row = encodeStudentRow(student);
    String sql = "INSERT INTO student_rows (rut, name, age, course_id) VALUES (?, ?, ?, ?)";
    try (Connection connection = connect();
        PreparedStatement insert = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
      bindStudentRow(insert, row);
      insert.executeUpdate();
      try (ResultSet keys = insert.getGeneratedKeys()) {
        keys.next();

        return decodeStudentRow(new StudentRow(keys.getLong(1), row.rut(), row.name(), row.age(), row.courseId()));
      }
    } catch (SQLException failure) {
      throw translateStoreError(failure);
    }
  }

  /** selectStudentRow Finds one Student, or Nothing. */
  @Override
  public Optional<Student> selectStudentRow(StudentId id) {
    List<Student> found = selectStudents("SELECT " + STUDENT_COLUMNS + " FROM student_rows WHERE id = ?", id.value());

    return found.stream().findFirst();
  }

  /** updateStudentRow Rewrites the Student its Id Names; false when nobody Holds it. */
  @Override
  public boolean updateStudentRow(Student student) {
    StudentRow row = encodeStudentRow(student);
    String sql = "UPDATE student_rows SET rut = ?, name = ?, age = ?, course_id = ? WHERE id = ?";
    try (Connection connection = connect(); PreparedStatement update = connection.prepareStatement(sql)) {
      bindStudentRow(update, row);
      update.setLong(5, row.id());

      return update.executeUpdate() > 0;
    } catch (SQLException failure) {
      throw translateStoreError(failure);
    }
  }

  /** deleteStudentRow Removes one Student; false when nobody Holds it. */
  @Override
  public boolean deleteStudentRow(StudentId id) {
    try (Connection connection = connect();
        PreparedStatement delete = connection.prepareStatement("DELETE FROM student_rows WHERE id = ?")) {
      delete.setLong(1, id.value());

      return delete.executeUpdate() > 0;
    } catch (SQLException failure) {
      throw translateStoreError(failure);
    }
  }

  /** selectStudentPage Reads one Page, Ordered by Name, Ties by Id. */
  @Override
  public List<Student> selectStudentPage(Page page) {
    return selectStudents("SELECT " + STUDENT_COLUMNS + " FROM student_rows ORDER BY name, id LIMIT ? OFFSET ?",
        page.size(), page.offset());
  }

  /** insertCourseRow Writes a new Course and Returns it Numbered. */
  @Override
  public Course insertCourseRow(Course course) {
    String sql = "INSERT INTO course_rows (code, name) VALUES (?, ?)";
    try (Connection connection = connect();
        PreparedStatement insert = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
      insert.setString(1, course.code().text());
      insert.setString(2, course.name().text());
      insert.executeUpdate();
      try (ResultSet keys = insert.getGeneratedKeys()) {
        keys.next();

        return course.withId(new CourseId(keys.getLong(1)));
      }
    } catch (SQLException failure) {
      throw translateStoreError(failure);
    }
  }

  /** selectCourseRow Finds one Course, or Nothing. */
  @Override
  public Optional<Course> selectCourseRow(CourseId id) {
    return selectCourses("SELECT " + COURSE_COLUMNS + " FROM course_rows WHERE id = ?", id.value())
        .stream().findFirst();
  }

  /** selectCoursePage Reads one Page of Courses, Ordered by Code, Ties by Id. */
  @Override
  public List<Course> selectCoursePage(Page page) {
    return selectCourses("SELECT " + COURSE_COLUMNS + " FROM course_rows ORDER BY code, id LIMIT ? OFFSET ?",
        page.size(), page.offset());
  }

  private List<Student> selectStudents(String sql, long... values) {
    try (Connection connection = connect(); PreparedStatement select = prepareWith(connection, sql, values);
        ResultSet rows = select.executeQuery()) {
      List<Student> students = new ArrayList<>();
      while (rows.next()) {
        students.add(decodeStudentRow(new StudentRow(rows.getLong("id"), rows.getString("rut"),
            rows.getString("name"), rows.getLong("age"), rows.getLong("course_id"))));
      }

      return students;
    } catch (SQLException failure) {
      throw translateStoreError(failure);
    }
  }

  private List<Course> selectCourses(String sql, long... values) {
    try (Connection connection = connect(); PreparedStatement select = prepareWith(connection, sql, values);
        ResultSet rows = select.executeQuery()) {
      List<Course> courses = new ArrayList<>();
      while (rows.next()) {
        courses.add(decodeCourseRow(new CourseRow(rows.getLong("id"), rows.getString("code"), rows.getString("name"))));
      }

      return courses;
    } catch (SQLException failure) {
      throw translateStoreError(failure);
    }
  }

  private static PreparedStatement prepareWith(Connection connection, String sql, long... values) throws SQLException {
    PreparedStatement statement = connection.prepareStatement(sql);
    for (int position = 0; position < values.length; position++) {
      statement.setLong(position + 1, values[position]);
    }

    return statement;
  }

  private static void bindStudentRow(PreparedStatement statement, StudentRow row) throws SQLException {
    statement.setString(1, row.rut());
    statement.setString(2, row.name());
    statement.setLong(3, row.age());
    statement.setLong(4, row.courseId());
  }

  private Connection connect() throws SQLException {
    return DriverManager.getConnection(url);
  }

  /**
   * translateStoreError Turns a driver Error into a Business Fault when it Means one.
   * A driver Error that Means nothing Stays Ours and Reaches the Edge as a 500.
   */
  static RuntimeException translateStoreError(SQLException failure) {
    if (UNIQUE_VIOLATION.equals(failure.getSQLState())) {
      return Errors.RUT_TAKEN;
    }

    return new IllegalStateException("the store Failed", failure);
  }

  static StudentRow encodeStudentRow(Student student) {
    return new StudentRow(student.id().value(), student.rut().text(), student.name().text(), student.age(),
        student.course().value());
  }

  static Student decodeStudentRow(StudentRow row) {
    return new Student(new StudentId(row.id()), new Rut(row.rut()), new FullName(row.name()), row.age(),
        new CourseId(row.courseId()));
  }

  static Course decodeCourseRow(CourseRow row) {
    return new Course(new CourseId(row.id()), new CourseCode(row.code()), new FullName(row.name()));
  }
}
